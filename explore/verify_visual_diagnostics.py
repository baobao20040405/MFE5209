"""Generates supplementary maps after execution to the official reporting stage and saves the only new Notebook module output."""
import os
import base64
import contextlib
import io
import pickle
import sys
from pathlib import Path
import nbformat
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from main import main
from visual_diagnostics import build_visual_diagnostics


def run():
    root=Path(__file__).resolve().parent
    # Old stages retain their calculations; suppress their repeated chart display only.
    original_show=plt.show
    plt.show=lambda *a,**k:plt.close('all')
    cache=root/'report_work'/'visual_context.pkl'
    if '--reuse' in sys.argv:
        context={'__name__':'__visual_validation__'}
        exec(compile((root/'config.py').read_text(encoding='utf-8'),str(root/'config.py'),'exec'),context)
        # This snapshot is generated by this script from the user's own local run.
        with cache.open('rb') as source:
            context.update(pickle.load(source))
        exec(compile((root/'models.py').read_text(encoding='utf-8'),str(root/'models.py'),'exec'),context)
        metric_source=(root/'reporting.py').read_text(encoding='utf-8').split('periods =',1)[0]
        exec(compile(metric_source,str(root/'reporting.py'),'exec'),context)
    else:
        context=main('reporting')
        with cache.open('wb') as destination:
            pickle.dump({key:context[key] for key in ['results','returns','assets','ALL_ASSETS','prices_sgd']},destination)
    context['PROJECT_ROOT']=root
    plt.show=original_show
    data=build_visual_diagnostics(context,show=False)
    notebook_path=root/'MFE5209_Global_Multi_Asset_Momentum_and_Risk_Allocation.ipynb'
    nb=nbformat.read(notebook_path,as_version=4)
    cell=next(cell for cell in nb.cells if cell.cell_type=='code' and cell.metadata.get('visual_diagnostics_appendix'))
    outputs=[]
    for key,path in data['figures'].items():
        outputs.append(nbformat.v4.new_output('display_data',data={
            'image/png':base64.b64encode(Path(path).read_bytes()).decode('ascii'),
            'text/plain':key}))
        outputs.append(nbformat.v4.new_output('stream',name='stdout',text=data['interpretations'][key]+'\n'))
    cell.outputs=outputs
    # Honest partial execution: new cell ran in equivalent reporting-stage context,
    # not an assertion that the complete Notebook was re-executed.
    cell.execution_count=None
    cell.metadata['validation']='Executed against freshly computed config/data/models/strategies/reporting context; unchanged later stress/attribution stages not rerun.'
    nbformat.validate(nb)
    nbformat.write(nb,notebook_path)
    print('NEW_FIGURES',len(data['figures']))


if __name__=='__main__':
    run()
